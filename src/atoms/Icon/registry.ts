export interface IconDefinition {
  /** Contenido del svg. Las partes que usan `currentColor` toman el `fill` del ícono. */
  Svg: () => JSX.Element
  /** viewBox por defecto. Si no se indica, '0 0 16 16'. */
  viewBox?: string
  /** Color por defecto de las partes con `currentColor`. Si no se indica, ziggurat. */
  fill?: string
  /** Ancho por defecto. Si no se indica, '1rem'. */
  w?: string
  /** Alto por defecto. Si no se indica, '1rem'. */
  h?: string
}

